-- snacks.nvim: picker, file explorer, dashboard, notifications, lazygit, zen, etc.
return {
    "folke/snacks.nvim",
    priority = 1000,
    lazy = false,
    opts = {
        bigfile = { enabled = true },
        quickfile = { enabled = true },
        dashboard = { enabled = true },
        explorer = { enabled = true, replace_netrw = true },
        picker = { enabled = true, ui_select = true },
        notifier = { enabled = true },
        input = { enabled = true },
        indent = { enabled = true },
        scope = { enabled = true },
        words = { enabled = true },
        statuscolumn = { enabled = true },
        lazygit = { enabled = true },
        zen = { enabled = true },
        rename = { enabled = true },
    },
    keys = {
        -- find (kept your old <leader>p* muscle memory)
        { "<leader>pf", function() Snacks.picker.files() end, desc = "Find files" },
        { "<C-p>", function() Snacks.picker.git_files() end, desc = "Git files" },
        { "<leader>ps", function() Snacks.picker.grep() end, desc = "Live grep" },
        { "<leader>pws", function() Snacks.picker.grep_word() end, desc = "Grep word" },
        { "<leader>pb", function() Snacks.picker.buffers() end, desc = "Buffers" },
        { "<leader>pr", function() Snacks.picker.recent() end, desc = "Recent files" },
        { "<leader>pd", function() Snacks.picker.diagnostics() end, desc = "Diagnostics" },
        { "<leader>pk", function() Snacks.picker.keymaps() end, desc = "Keymaps" },
        { "<leader>pp", function() Snacks.picker.resume() end, desc = "Resume picker" },
        { "<leader>pu", function() Snacks.picker.undo() end, desc = "Undo history" },
        { "<leader>pt", function() Snacks.picker.todo_comments() end, desc = "TODOs" },
        { "<leader>/", function() Snacks.picker.lines() end, desc = "Search buffer" },
        { "<leader>vh", function() Snacks.picker.help() end, desc = "Help" },
        { "<leader>pc", function() Snacks.picker.files({ cwd = vim.fn.stdpath("config") }) end, desc = "Config files" },
        -- explorer
        { "<leader>pe", function() Snacks.explorer() end, desc = "File tree" },
        -- git
        { "<leader>gg", function() Snacks.lazygit() end, desc = "Lazygit" },
        { "<leader>gl", function() Snacks.picker.git_log() end, desc = "Git log" },
        { "<leader>gs", function() Snacks.picker.git_status() end, desc = "Git status" },
        { "<leader>gb", function() Snacks.git.blame_line() end, desc = "Blame line" },
        { "<leader>gB", function() Snacks.gitbrowse() end, desc = "Open in browser", mode = { "n", "v" } },
        -- lsp
        { "gd", function() Snacks.picker.lsp_definitions() end, desc = "Goto definition" },
        { "gD", function() Snacks.picker.lsp_declarations() end, desc = "Goto declaration" },
        { "gy", function() Snacks.picker.lsp_type_definitions() end, desc = "Goto type def" },
        { "<leader>ls", function() Snacks.picker.lsp_symbols() end, desc = "Symbols" },
        { "<leader>lS", function() Snacks.picker.lsp_workspace_symbols() end, desc = "Workspace symbols" },
        { "]]", function() Snacks.words.jump(vim.v.count1) end, desc = "Next reference" },
        { "[[", function() Snacks.words.jump(-vim.v.count1) end, desc = "Prev reference" },
        -- misc
        { "<leader>zz", function() Snacks.zen() end, desc = "Zen mode" },
        { "<leader>zZ", function() Snacks.zen.zoom() end, desc = "Zoom window" },
        { "<leader>n", function() Snacks.notifier.show_history() end, desc = "Notifications" },
        { "<leader>bd", function() Snacks.bufdelete() end, desc = "Delete buffer" },
        { "<C-/>", function() Snacks.terminal() end, desc = "Terminal", mode = { "n", "t" } },
    },
}
